export function ref(key) {
  const pair = C[key];
  if (!pair) throw new Error(`missing cite ${key}`);
  return { label: pair[0], url: pair[1] };
}

export function lesson(spec) {
  const cite = ref(spec.cite);
  const nodes = spec.nodes.map((node, index) => ({
    id: `n${index}`,
    label: node[0],
    sub: node[1] || "",
    x: node[2],
    y: node[3],
    tone: node[4] || (index % 4) + 1,
    w: 168,
    h: 66,
  }));
  const lessonObject = {
    id: spec.id,
    title: spec.title,
    level: spec.level,
    minutes: spec.minutes,
    summary: spec.summary,
    uncertainty: spec.uncertainty || "",
    objectives: spec.objectives,
    diagram: {
      caption: spec.caption,
      nodes,
      edges: spec.edges.map(([from, to, label]) => ({ from: `n${from}`, to: `n${to}`, label: label || "" })),
    },
    flow: {
      title: spec.flowTitle,
      steps: spec.steps.map((step) => ({
        from: step[0], to: step[1], label: step[2], detail: step[3], inspect: step[4], cite: cite.url,
      })),
    },
    sections: spec.sections.map((section) => ({
      h: section[0],
      paragraphs: section[1],
      cite: ref(section[2] || spec.cite),
    })),
    quiz: spec.quiz.map((row) => ({
      q: row[0],
      choices: [row[1], row[2], row[3], row[4]],
      answer: 0,
      why: row[5],
      cite: ref(row[6] || spec.cite).url,
    })),
    cards: spec.cards.map(([front, back]) => ({ front, back })),
    lab: {
      title: spec.lab[0],
      goal: spec.lab[1],
      steps: spec.lab[2].map(([doText, expect]) => ({ do: doText, expect })),
      check: spec.lab[3],
    },
    fault: {
      title: spec.fault[0],
      symptom: spec.fault[1],
      log: spec.fault[2],
      cause: spec.fault[3],
      fix: spec.fault[4],
      cite: ref(spec.fault[5] || spec.cite),
    },
  };
  const problems = [];
  if (lessonObject.quiz.length < 6) problems.push("quiz");
  if (lessonObject.cards.length < 4) problems.push("cards");
  if (lessonObject.flow.steps.length < 4) problems.push("flow");
  if (lessonObject.sections.length < 2) problems.push("sections");
  if (lessonObject.lab.steps.length < 3) problems.push("lab");
  if (!lessonObject.diagram.nodes.length) problems.push("diagram");
  if (problems.length) throw new Error(`${spec.id} missing ${problems.join(",")}`);
  return lessonObject;
}

export function track(meta, lessons) {
  if (lessons.length < 7) throw new Error(`${meta.id} has ${lessons.length} lessons`);
  return { ...meta, lessons };
}
