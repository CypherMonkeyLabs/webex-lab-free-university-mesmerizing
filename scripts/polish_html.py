def brand_js():
    # Brand chrome is the website, the GitHub organization, and Linktree. No other social icons.
    js = "/* Generated by scripts/polish_html.py. Brand icons, drawn inline. */\n(function(){\nvar M=" + json.dumps(monkey("@@")) + ";\nvar L=" + json.dumps(linktree("@@")) + ";\n" \
        "window.CANON_BRAND={monkey:function(k){return M.split('@@').join(k||'a');},github:" + json.dumps(GITHUB) + ",linktree:function(k){return L.split('@@').join(k||'a');}};\n})();\n"
    (ROOT / "assets/js/brand.js").write_text(js)

FORBIDDEN_ANCHOR = re.compile(
    r'\s*<a\b[^>]*href="https?://(?:(?:www\.)?x\.com/|(?:www\.)?linkedin\.com/|huggingface\.co/|github\.com/cipher0x9)[^"]*"[^>]*>.*?</a>',
    re.I | re.S)
RATE_ANCHOR = re.compile(
    r'\s*<a\b[^>]*href="https://github\.com/CypherMonkeyLabs/webex-lab-free-university-mesmerizing"[^>]*>.*?</a>',
    re.I | re.S)

def clean_meta(meta):
    meta = FORBIDDEN_ANCHOR.sub("", meta)
    meta = RATE_ANCHOR.sub("", meta)
    return meta

